/**
 * Create PRs for enrichment branches using the MMDB GitHub App bot.
 * 
 * Uses the same auth as the ingestion pipeline (GitHub App, not personal tokens).
 * Expects GITHUB_APP_ID, GITHUB_APP_PRIVATE_KEY, GITHUB_APP_INSTALLATION_ID in env.
 * 
 * Usage:
 *   npx tsx tools/src/create-enrichment-prs.ts                    # dry run
 *   npx tsx tools/src/create-enrichment-prs.ts --live             # create PRs
 *   npx tsx tools/src/create-enrichment-prs.ts --live --year=2026 # single year
 */

import { createOctokit } from '../../functions/src/ingestion/auth.js';
import { GITHUB_ORG } from '../../functions/src/config.js';

// --- Enrichment configs (select via --branch flag) ---
const ENRICHMENT_CONFIGS: Record<string, { branch: string; title: string; body: string }> = {
  'enrichment/genres-isadult': {
    branch: 'enrichment/genres-isadult',
    title: 'feat: enrich genres + is_adult from IMDB bulk data',
    body: `## Automated Enrichment

Adds \`genres\` (string[]) and \`is_adult\` (boolean) to movie and series JSON files.

**Sources:**
- IMDB \`title.basics.tsv.gz\` bulk dataset (87.6% of titles)
- Wikidata batch SPARQL fallback (12.4% without IMDB ID)

**Coverage achieved:** ~94% genre population (from 0%)

**Fields added:**
- \`genres\`: up to 3 genres per title (e.g., ["Drama", "Fantasy"])
- \`is_adult\`: boolean — true only for pornographic content (same classification as IMDB/TMDB)

---
*Generated by enrich-from-imdb.ts — TASK-143*`,
  },
  'enrichment/countries': {
    branch: 'enrichment/countries',
    title: 'feat: add countries from Wikidata P495',
    body: `## Automated Enrichment

Adds \`countries\` (string[]) field to movie and series JSON files.

**Source:** Wikidata P495 (country of origin) → P297 (ISO 3166-1 alpha-2 code)

**Coverage achieved:** ~95.6% (150,648 / 157,588 titles)

**Field added:**
- \`countries\`: ISO alpha-2 codes, sorted, e.g. ["FR"], ["US"], ["CA", "DE", "GB", "US"]

Titles without P495 data receive an empty array \`[]\`.

---
*Generated by enrich-countries.ts — TASK-145*`,
  },
};

const args = process.argv.slice(2);
const branchFlag = args.find(a => a.startsWith('--branch='));
const selectedBranch = branchFlag ? branchFlag.split('=')[1] : 'enrichment/countries';
const config = ENRICHMENT_CONFIGS[selectedBranch] || {
  branch: selectedBranch,
  title: `feat: enrichment from ${selectedBranch}`,
  body: `## Automated Enrichment\n\nBranch: ${selectedBranch}`,
};

const BRANCH_NAME = config.branch;
const BASE_BRANCH = 'master';
const PR_TITLE = config.title;
const PR_BODY = config.body;

const YEARS = Array.from({ length: 27 }, (_, i) => 2000 + i);

async function main() {
  const dryRun = !args.includes('--live');
  const yearFlag = args.find(a => a.startsWith('--year='));
  const targetYears = yearFlag 
    ? [parseInt(yearFlag.split('=')[1])] 
    : YEARS;

  console.log(`\n🔧 MMDB Enrichment PR Creator`);
  console.log(`   Mode: ${dryRun ? '🧪 DRY RUN' : '⚡ LIVE'}`);
  console.log(`   Years: ${targetYears.length === 1 ? targetYears[0] : `${targetYears[0]}-${targetYears[targetYears.length - 1]}`}`);
  console.log(`   Branch: ${BRANCH_NAME}\n`);

  if (dryRun) {
    console.log('   (pass --live to actually create PRs)\n');
  }

  const octokit = createOctokit();
  let created = 0;
  let skipped = 0;
  let errors = 0;

  for (const year of targetYears) {
    const repo = `mmdb-${year}`;
    
    try {
      // Check if branch exists
      try {
        await octokit.rest.repos.getBranch({
          owner: GITHUB_ORG,
          repo,
          branch: BRANCH_NAME,
        });
      } catch (e: any) {
        if (e.status === 404) {
          console.log(`   ⏭️  ${repo}: branch not found, skipping`);
          skipped++;
          continue;
        }
        throw e;
      }

      // Check if PR already exists for this branch
      const { data: existingPrs } = await octokit.rest.pulls.list({
        owner: GITHUB_ORG,
        repo,
        head: `${GITHUB_ORG}:${BRANCH_NAME}`,
        state: 'open',
      });

      if (existingPrs.length > 0) {
        console.log(`   ✅ ${repo}: PR already exists (#${existingPrs[0].number})`);
        skipped++;
        continue;
      }

      if (dryRun) {
        console.log(`   📋 ${repo}: would create PR`);
        created++;
        continue;
      }

      // Create PR
      const { data: pr } = await octokit.rest.pulls.create({
        owner: GITHUB_ORG,
        repo,
        title: PR_TITLE,
        body: PR_BODY,
        head: BRANCH_NAME,
        base: BASE_BRANCH,
      });

      console.log(`   ✅ ${repo}: PR #${pr.number} created`);

      // Enable auto-merge if available
      try {
        await octokit.graphql(`
          mutation EnableAutoMerge($pullRequestId: ID!) {
            enablePullRequestAutoMerge(input: {
              pullRequestId: $pullRequestId
              mergeMethod: SQUASH
            }) {
              pullRequest { number }
            }
          }
        `, { pullRequestId: pr.node_id });
        console.log(`         auto-merge enabled`);
      } catch {
        // auto-merge might not be available on repo settings
      }

      created++;

      // Rate limit: 200ms between API calls
      await new Promise(r => setTimeout(r, 200));
    } catch (e: any) {
      console.log(`   ❌ ${repo}: ${e.message}`);
      errors++;
    }
  }

  console.log(`\n📊 Results: ${created} created, ${skipped} skipped, ${errors} errors\n`);
}

main().catch(e => {
  console.error(`\n❌ Fatal: ${e.message}`);
  process.exit(1);
});
